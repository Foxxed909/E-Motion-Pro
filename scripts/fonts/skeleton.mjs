// E-Motion Pro type skeleton.
// One original set of centre-line letterforms, cap height 700, baseline 0.
// Every typeface in the family is a different way of "drawing" these lines.
// Lowercase letters are mapped to the same glyphs (the fonts are display caps).

const STEP = 10; // sampling distance for curves, in font units

/** Sample an elliptical arc. Angles in degrees, counter-clockwise, 0 = +x. */
export function arc(cx, cy, rx, ry, a0, a1) {
  const span = Math.abs(a1 - a0) * (Math.PI / 180);
  const n = Math.max(6, Math.ceil((span * Math.max(rx, ry)) / STEP));
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

/** Join point lists into one polyline, removing duplicated joints. */
export function P(...parts) {
  const out = [];
  for (const part of parts) {
    const pts = typeof part[0] === "number" ? [part] : part;
    for (const p of pts) {
      const last = out[out.length - 1];
      if (last && Math.hypot(last[0] - p[0], last[1] - p[1]) < 0.5) continue;
      out.push([p[0], p[1]]);
    }
  }
  return out;
}

